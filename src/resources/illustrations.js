export function getIllustrationSvg(name) {
  if (!name) return null;
  const clean = String(name).toLowerCase().trim().replace(/s$/, '');
  if (ILLUSTRATIONS[clean]) return ILLUSTRATIONS[clean];
  if (clean === 'pencile') return ILLUSTRATIONS.pencil;
  if (clean === 'table') return ILLUSTRATIONS.desk;
  if (clean === 'backpack') return ILLUSTRATIONS.bag;
  return null;
}
